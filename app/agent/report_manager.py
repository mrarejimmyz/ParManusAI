        """Create an intelligent report by analyzing search results"""
        report_name = self.generate_report_name(task_description)
        report_path = os.path.join(self.workspace_path, report_name)

        # Analyze search results to generate intelligent content
        if search_results:
            # Extract key information from search results
            sources_text = ""
            for i, result in enumerate(search_results[:5], 1):
                title = result.get("title", "N/A")
                url = result.get("url", "N/A")
                content = result.get("content", result.get("snippet", "N/A"))[:500]
                sources_text += (
                    f"Source {i}: {title}\nURL: {url}\nContent: {content}...\n\n"
                )

            # Generate intelligent content based on search data
            if "kathmandu" in task_description.lower():
                content = self._create_kathmandu_report(
                    task_description, search_results
                )
