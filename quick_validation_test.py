def create_test_report():
    """Create a test report to validate file creation works"""
    print("\n📝 CREATING TEST REPORT")
    print("=" * 40)

    try:
        workspace_dir = "workspace"
        os.makedirs(workspace_dir, exist_ok=True)

        test_report_content = f"""# Test Report - {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}

## Purpose
This is a test report to validate that the file system operations are working correctly.

## System Information
- Timestamp: {datetime.now().isoformat()}
- Workspace: {os.path.abspath(workspace_dir)}
- Working Directory: {os.getcwd()}

## Test Results
- File creation: ✅ Working
- Content writing: ✅ Working
- Directory management: ✅ Working

## Validation Checks
1. **File System Access**: Can create files and directories
2. **Content Generation**: Can write structured content
3. **Workspace Management**: Proper file organization

## Conclusion
The core file system functionality is operational and ready for report generation tasks.

---
*Generated by: Test validation script*
*Status: System operational*
"""

        test_file = os.path.join(workspace_dir, "system_validation_test.md")
        with open(test_file, "w", encoding="utf-8") as f:
            f.write(test_report_content)

        print(f"✅ Test report created: {test_file}")
        print(f"📏 Size: {len(test_report_content)} characters")

        # Verify the file
        if os.path.exists(test_file):
            actual_size = os.path.getsize(test_file)
            print(f"📊 Verified size: {actual_size} bytes")
            return True
        else:
            print("❌ File verification failed")
            return False

    except Exception as e:
        print(f"❌ Test report creation failed: {e}")
        return False


def main():
    """Run quick validation tests"""
    print("🚀 QUICK REPORT & SYSTEM VALIDATION")
    print("=" * 50)

    results = {}

    # Test 1: Validate existing reports
    results["existing_reports"] = validate_existing_reports()

    # Test 2: Check agent components
    results["agent_components"] = check_agent_components()

    # Test 3: Create test report
    results["test_report"] = create_test_report()

    # Summary
    print("\n" + "=" * 50)
    print("📋 VALIDATION SUMMARY")
    print("=" * 50)

    passed = sum(1 for result in results.values() if result)
    total = len(results)

    print(f"📊 Results: {passed}/{total} tests passed")

    for test_name, result in results.items():
        status = "✅ PASS" if result else "❌ FAIL"
        print(f"  {status} {test_name.replace('_', ' ').title()}")

    # Final assessment
    if passed == total:
        print("\n🎉 ALL SYSTEMS OPERATIONAL")
        print("✅ Report generation infrastructure working correctly")
        print("✅ Agent components accessible")
        print("✅ File system operations functional")
    elif passed >= total * 0.7:
        print("\n⚠️ MOSTLY OPERATIONAL")
        print("🔧 Minor issues detected but core functionality working")
    else:
        print("\n❌ SIGNIFICANT ISSUES")
        print("🚨 Core functionality problems detected")

    print(f"\n📁 Check the 'workspace' directory for generated reports and test files.")

    return passed >= total * 0.7


if __name__ == "__main__":
    main()
