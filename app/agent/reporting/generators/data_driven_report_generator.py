"""
Data-Driven Report Generator
Handles creation of reports from search data with LLM intelligence
"""

import os
from datetime import datetime
from typing import Dict, List, Optional

from app.logger import logger


class DataDrivenReportGenerator:
    """Generates reports based on search results and data analysis"""

    def __init__(self, workspace_path: str = "workspace"):
        self.workspace_path = workspace_path
        os.makedirs(workspace_path, exist_ok=True)

    async def create_llm_driven_report(
        self, task_description: str, search_results: List[Dict], report_name: str
    ) -> str:
        """Create intelligent report using LLM analysis of search results"""
        try:
            from app.config import load_config
            from app.llm import LLM

            config = load_config()
            llm = LLM(config.llm)

            report_path = os.path.join(self.workspace_path, report_name)

            if not search_results:
                # Create knowledge-based report when no search data
                content = await self._create_knowledge_based_report(
                    llm, task_description
                )
            else:
                # Create data-driven report from search results
                content = await self._create_search_data_report(
                    llm, task_description, search_results
                )

            with open(report_path, "w", encoding="utf-8") as f:
                f.write(content)

            logger.info(f"📝 Created LLM-driven report: {report_name}")
            return report_path

        except Exception as e:
            logger.error(f"❌ Error creating LLM-driven report: {e}")
            return self._create_data_driven_fallback(
                task_description, search_results, report_name
            )

    async def _create_knowledge_based_report(self, llm, task_description: str) -> str:
        """Create report based on LLM knowledge when no search data available"""

        prompt = f"""Create a comprehensive, factual report for this task:

TASK: {task_description}

Since no relevant search data was found, use your knowledge to provide a factual analysis.

REQUIREMENTS:
- Be factual and accurate - no speculation or made-up details
- Provide logical reasoning and analysis
- Use clear structure with Executive Summary, Key Findings, Recommendations, Next Steps
- Clearly state when information is based on general knowledge vs. specific sources
- If the topic involves current events you're not sure about, acknowledge limitations

Create a professional report that addresses the task comprehensively while being transparent about information sources.

FORMAT:
# Report: [Task Title]

**Generated:** {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}

[Rest of report content...]

Include completion checklist at the end."""

        try:
            content = await llm.ask(prompt)

            # Ensure proper formatting and add metadata
            if not content.startswith("# Report:"):
                formatted_content = f"""# Report: {task_description}

**Generated:** {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}

{content}

## Completion Checklist

- [x] ✅ **Executive Summary** - LLM-generated analysis completed
- [x] ✅ **Key Findings** - Knowledge-based insights documented
- [x] ✅ **Recommendations** - Actionable advice provided
- [x] ✅ **Next Steps** - Implementation plan outlined
- [x] ✅ **AI Analysis** - Intelligent content generation completed
- [ ] 📝 **Additional Research** - Further investigation if needed
- [ ] 📝 **Validation** - Verify findings with current sources
- [ ] 📝 **Implementation** - Execute recommended actions

---
*Report generated by ParManus using AI knowledge base*
"""
                return formatted_content

            return content

        except Exception as e:
            logger.error(f"Error generating knowledge-based report: {e}")
            return self._create_basic_fallback_report(task_description)

    async def _create_search_data_report(
        self, llm, task_description: str, search_results: List[Dict]
    ) -> str:
        """Create report based on validated search results"""

        # Prepare search data for LLM analysis
        sources_text = ""
        for i, result in enumerate(search_results[:5], 1):
            title = result.get("title", "N/A")
            content = result.get("content", result.get("snippet", ""))[:400]
            url = result.get("url", "N/A")
            sources_text += (
                f"\nSource {i}:\nTitle: {title}\nURL: {url}\nContent: {content}...\n"
            )

        prompt = f"""Create a comprehensive report based on the provided sources:

TASK: {task_description}

VALIDATED SOURCES:
{sources_text}

REQUIREMENTS:
- Base your analysis primarily on the provided sources
- Synthesize information from multiple sources when possible
- Provide clear executive summary and key findings
- Include actionable recommendations based on the source material
- Reference sources appropriately in your analysis
- Be factual - don't add information not supported by the sources
- If sources are limited, acknowledge this and focus on what can be determined

Create a professional, well-structured report that makes the best use of the available source material.

FORMAT:
# Report: [Task Title]

**Generated:** {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}

## Executive Summary
[Overview based on sources]

## Key Findings
[Analysis of source information]

## Recommendations
[Actionable advice based on findings]

## Next Steps
[Implementation suggestions]

## Sources
[List the sources referenced]

Include completion checklist at the end."""

        try:
            content = await llm.ask(prompt)

            # Add sources section if not included
            if "## Sources" not in content:
                content += "\n\n## Research Data\n\n"
                for i, result in enumerate(search_results[:5], 1):
                    content += f"### Source {i}: {result.get('title', 'N/A')}\n"
                    content += f"**URL:** {result.get('url', 'N/A')}\n"
                    content += f"**Content:** {result.get('content', result.get('snippet', 'N/A'))[:500]}...\n\n"

            # Add completion checklist if not included
            if "Completion Checklist" not in content:
                content += """
## Completion Checklist

- [x] ✅ **Executive Summary** - Data-driven analysis completed
- [x] ✅ **Key Findings** - Source-based insights documented
- [x] ✅ **Recommendations** - Evidence-based advice provided
- [x] ✅ **Next Steps** - Implementation plan outlined
- [x] ✅ **Research Data** - Sources analyzed and integrated
- [x] ✅ **AI Analysis** - Intelligent synthesis completed
- [ ] 📝 **Follow-up Research** - Additional investigation if needed
- [ ] 📝 **Implementation** - Execute recommended actions

---
*Report generated by ParManus using validated search data*
"""

            return content

        except Exception as e:
            logger.error(f"Error generating search data report: {e}")
            return self._create_basic_search_summary(task_description, search_results)

    def _create_data_driven_fallback(
        self, task_description: str, search_results: List[Dict], report_name: str
    ) -> str:
        """Create fallback report when LLM is unavailable"""

        report_path = os.path.join(self.workspace_path, report_name)

        if search_results:
            content = self._create_basic_search_summary(
                task_description, search_results
            )
        else:
            content = self._create_basic_fallback_report(task_description)

        with open(report_path, "w", encoding="utf-8") as f:
            f.write(content)

        logger.info(f"📝 Created fallback report: {report_name}")
        return report_path

    def _create_basic_search_summary(
        self, task_description: str, search_results: List[Dict]
    ) -> str:
        """Create basic summary of search results"""

        current_time = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

        content = f"""# Report: {task_description}

**Generated:** {current_time}

## Executive Summary

This report summarizes findings from {len(search_results)} search results related to: "{task_description}"

## Key Findings

Based on the search results:
"""

        # Add key points from search results
        for i, result in enumerate(search_results[:3], 1):
            title = result.get("title", "N/A")
            content += f"- **Finding {i}**: {title}\n"

        content += """
## Recommendations

- Review the detailed source materials below
- Conduct additional research for comprehensive analysis
- Validate findings with authoritative sources
- Develop specific action plans based on findings

## Next Steps

1. **Detailed Analysis** - Examine each source thoroughly
2. **Cross-Reference** - Verify information across multiple sources
3. **Expert Consultation** - Seek domain expert opinions if needed
4. **Implementation Planning** - Develop concrete action plans

## Research Data

"""

        # Add all search results
        for i, result in enumerate(search_results, 1):
            content += f"""### Source {i}: {result.get('title', 'N/A')}
**URL:** {result.get('url', 'N/A')}
**Content:** {result.get('content', result.get('snippet', 'N/A'))[:500]}...

"""

        content += """## Completion Checklist

- [x] ✅ **Search Results** - Collected and organized
- [x] ✅ **Basic Summary** - Overview provided
- [ ] 📝 **Detailed Analysis** - In-depth examination needed
- [ ] 📝 **Expert Review** - Subject matter expert consultation
- [ ] 📝 **Action Plan** - Specific implementation steps
- [ ] 📝 **Final Report** - Comprehensive analysis document

---
*Basic report generated from search results*
"""

        return content

