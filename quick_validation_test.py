import json
import os
from datetime import datetime


def validate_existing_reports():
    """Validate existing report files"""
    print("🔍 VALIDATING EXISTING REPORTS")
    print("=" * 40)

    workspace_dir = "workspace"
    if not os.path.exists(workspace_dir):
        print(f"❌ Workspace directory not found: {workspace_dir}")
        return False

    # Find all markdown files
    report_files = []
    for root, dirs, files in os.walk(workspace_dir):
        for file in files:
            if file.endswith(".md"):
                file_path = os.path.join(root, file)
                report_files.append(file_path)

    print(f"📊 Found {len(report_files)} markdown files:")

    valid_reports = 0
    for report_file in report_files:
        file_size = os.path.getsize(report_file)
        print(f"\n📄 {report_file}")
        print(f"  📏 Size: {file_size} bytes")

        if file_size > 0:
            with open(report_file, "r", encoding="utf-8", errors="ignore") as f:
                content = f.read()

            # Analyze content
            lines = content.splitlines()
            words = content.split()
            sections = content.count("#")

            print(f"  📖 Lines: {len(lines)}")
            print(f"  📝 Words: {len(words)}")
            print(f"  🗂️ Sections: {sections}")

            # Quality assessment
            if len(words) > 50 and sections > 0:
                print(f"  ✅ Valid report")
                valid_reports += 1

                # Show first few lines
                preview_lines = lines[:3]
                for i, line in enumerate(preview_lines):
                    if line.strip():
                        print(f"  📖 {line[:80]}...")
                        break
            else:
                print(f"  ⚠️ Empty or minimal content")
        else:
            print(f"  ❌ Empty file")

    print(f"\n📊 Summary: {valid_reports}/{len(report_files)} valid reports")
    return valid_reports > 0


